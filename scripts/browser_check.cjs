const { chromium } = require('../frontend/node_modules/playwright');
const fs=require('fs');
const path=require('path');
const assert=require('node:assert/strict');
(async()=>{
 const out=path.resolve('output/qa');fs.mkdirSync(out,{recursive:true});
 const browser=await chromium.launch({...(process.platform==='win32'?{channel:'msedge'}:{}),headless:true});
 const page=await browser.newPage({viewport:{width:1512,height:1100},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.APP_URL||'http://127.0.0.1:5173');
 await page.getByRole('heading',{name:'Fleet activity',exact:true}).waitFor();
 await page.waitForTimeout(2000);
 await page.getByRole('combobox',{name:'Vessel type'}).selectOption('Cargo');
 await page.waitForResponse(r=>r.url().includes('/api/vessels?')&&r.url().includes('vessel_type=Cargo'));
 assert.ok(await page.locator('tbody tr').count()>0);
 await page.getByRole('combobox',{name:'Vessel type'}).selectOption('All');
 await page.getByRole('textbox',{name:'Search vessels'}).fill('no-such-vessel-987654');
 await page.getByText('No vessels match these filters.').waitFor();
 await page.getByRole('textbox',{name:'Search vessels'}).fill('');
 await page.getByRole('button',{name:'Inspect',exact:false}).first().waitFor();
 const downloadEvent=page.waitForEvent('download');
 await page.getByRole('link',{name:'Export data',exact:true}).click();
 const download=await downloadEvent;
 assert.equal(download.suggestedFilename(),'ais_observations.csv');
 await page.getByRole('button',{name:'Open project walkthrough',exact:true}).click();
 await page.getByRole('dialog').waitFor();
 await page.keyboard.press('Escape');
 assert.equal(await page.getByRole('dialog').count(),0);
 await page.screenshot({path:path.join(out,'01-fleet.png'),fullPage:true});
 await page.getByRole('button',{name:'Inspect',exact:false}).first().click();
 await page.getByText('NEXT OBSERVED SPEED ESTIMATE',{exact:true}).waitFor();
 await page.screenshot({path:path.join(out,'02-vessel.png'),fullPage:true});
 await page.getByRole('button',{name:'Explore the data',exact:true}).click();
 await page.getByRole('heading',{name:'Speed distribution'}).waitFor();
 await page.screenshot({path:path.join(out,'03-eda.png'),fullPage:true});
 await page.getByRole('button',{name:'Scenario lab',exact:true}).click();
 await page.getByRole('button',{name:'Severe weather',exact:true}).click();
 await page.getByRole('button',{name:'Evaluate scenario',exact:true}).click();
 await page.getByRole('heading',{name:'Decision briefing'}).waitFor();
 await page.getByRole('button',{name:'Save experiment',exact:true}).click();
 await page.getByRole('status').waitFor();
 await page.screenshot({path:path.join(out,'04-scenario.png'),fullPage:true});
 await page.getByRole('button',{name:'Delete Severe weather',exact:true}).first().click();
 await page.getByRole('button',{name:'Model benchmark',exact:true}).click();
 await page.getByRole('heading',{name:'Experimental comparison'}).waitFor();
 await page.screenshot({path:path.join(out,'05-benchmark.png'),fullPage:true});
 await page.getByRole('button',{name:'Data & methodology',exact:true}).click();
 await page.screenshot({path:path.join(out,'06-methodology.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Fleet overview',exact:false}).click();
 await page.screenshot({path:path.join(out,'07-mobile.png'),fullPage:true});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 const offline=await browser.newPage({viewport:{width:1280,height:900}});
 await offline.route(/^https:\/\//,route=>route.abort());
 await offline.goto(process.env.APP_URL||'http://127.0.0.1:5173');
 await offline.getByRole('heading',{name:'Fleet activity',exact:true}).waitFor();

 await offline.locator('.leaflet-overlay-pane path:visible').first().waitFor();
 console.log(JSON.stringify({errors,mobileOverflow:overflow,screenshots:7,searchFiltersExportModal:true,offlineMap:true},null,2));
 await browser.close();if(errors.length||overflow)process.exitCode=1;
})().catch(e=>{console.error(e);process.exit(1)});
